-- ATENCAO: o numero V8 e uma sugestao para a base com V1..V7.
-- Antes de usar, confira flyway_schema_history e renumere V8,
-- V9 e V10 se ja existir migracao posterior.
--
-- Esta migracao nao altera nem remove dados existentes. Cria o
-- schema pkg_petjourney (que no PostgreSQL faz o papel de agrupador
-- das rotinas, ja que o PostgreSQL nao tem packages) e as duas
-- tabelas tecnicas: tb_auditoria e tb_log_erro.
-- ============================================================

-- Pre-condicoes: versao do servidor e tabelas de dominio existentes.
DO $$
DECLARE
    v_tabela text;
    v_faltando text := '';
BEGIN
    IF current_setting('server_version_num')::int < 130000 THEN
        RAISE EXCEPTION 'PetJourney exige PostgreSQL 13 ou superior (versao atual: %).',
            current_setting('server_version');
    END IF;

    FOREACH v_tabela IN ARRAY ARRAY['tb_clinica','tb_tutor','tb_veterinario','tb_pet',
        'tb_disponibilidade_veterinario','tb_agendamento','tb_prontuario','tb_medicamento','tb_usuario']
    LOOP
        IF to_regclass('public.' || v_tabela) IS NULL THEN
            v_faltando := v_faltando || ' ' || v_tabela;
        END IF;
    END LOOP;

    IF v_faltando <> '' THEN
        RAISE EXCEPTION 'Tabelas de dominio ausentes no schema public:%. Aplique antes as migracoes V1 a V7 do Java.', v_faltando;
    END IF;
END
$$;

CREATE SCHEMA IF NOT EXISTS pkg_petjourney;
COMMENT ON SCHEMA pkg_petjourney IS
    'Rotinas do PetJourney (procedures, funcoes e funcoes de gatilho). Equivale ao package Oracle da Sprint 3; o PostgreSQL agrupa objetos por schema.';

-- ------------------------------------------------------------
-- Auditoria de agendamento. Sem FK para tb_agendamento: o
-- historico precisa sobreviver ao DELETE do agendamento.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.tb_auditoria (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    db_username    text         NOT NULL,
    operation      varchar(6)   NOT NULL,
    occurred_at    timestamptz  NOT NULL,
    appointment_id bigint,
    old_values     text,
    new_values     text,
    app_username   text,
    correlation_id text,
    CONSTRAINT chk_auditoria_operation CHECK (operation IN ('INSERT','UPDATE','DELETE'))
);

CREATE INDEX IF NOT EXISTS idx_tb_auditoria_appointment ON public.tb_auditoria (appointment_id);

COMMENT ON TABLE  public.tb_auditoria IS 'Auditoria de INSERT, UPDATE e DELETE em tb_agendamento. Nao armazena senha nem codigo de primeiro acesso.';
COMMENT ON COLUMN public.tb_auditoria.db_username    IS 'Usuario de banco (o usuario JDBC e compartilhado pela aplicacao).';
COMMENT ON COLUMN public.tb_auditoria.occurred_at    IS 'Instante real da operacao, com fuso.';
COMMENT ON COLUMN public.tb_auditoria.appointment_id IS 'Id do agendamento; sem FK para o historico sobreviver ao DELETE.';
COMMENT ON COLUMN public.tb_auditoria.app_username   IS 'Usuario da aplicacao, lido de petjourney.app_username quando o Java o define na transacao.';
COMMENT ON COLUMN public.tb_auditoria.correlation_id IS 'Id de correlacao, lido de petjourney.correlation_id quando definido.';

-- ------------------------------------------------------------
-- Log de erros. A persistencia apos ROLLBACK e feita pelo Java,
-- chamando pkg_petjourney.prc_log_erro em transacao separada
-- (o PostgreSQL nao tem PRAGMA AUTONOMOUS_TRANSACTION).
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.tb_log_erro (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    routine_name   text        NOT NULL,
    db_username    text        NOT NULL,
    occurred_at    timestamptz NOT NULL,
    sqlstate       char(5),
    message        text,
    correlation_id text
);

CREATE INDEX IF NOT EXISTS idx_tb_log_erro_occurred_at ON public.tb_log_erro (occurred_at DESC);

COMMENT ON TABLE  public.tb_log_erro IS 'Log tecnico de erros das rotinas. Nunca registrar senha, codigo de primeiro acesso ou token.';
COMMENT ON COLUMN public.tb_log_erro.sqlstate IS 'SQLSTATE de 5 caracteres. Erros de dominio do PetJourney usam PJ + 3 digitos (ver docs/contratos_banco.md).';
